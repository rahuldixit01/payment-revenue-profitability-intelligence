
import getpass
import csv
from pathlib import Path

from sqlalchemy import create_engine, text
from sqlalchemy.engine import URL


DATA_DIR = Path(__file__).resolve().parent

# Load parent tables before dependent tables.
TABLES = [
    ("merchants", "merchants.csv"),
    ("transactions", "transactions.csv"),
    ("transaction_fees", "transaction_fees.csv"),
    ("settlements", "settlements.csv"),
    ("refunds", "refunds.csv"),
    ("chargebacks", "chargebacks.csv"),
    ("reconciliation_exceptions", "reconciliation_exceptions.csv"),
]


def connect_to_database():
    username = input("Enter PostgreSQL username: ")
    password = getpass.getpass("Enter PostgreSQL password: ")

    url = URL.create(
        drivername="postgresql+psycopg",
        username=username,
        password=password,
        host="localhost",
        port=5432,
        database="payment_intelligence",
    )

    return create_engine(url)


def load_csv(connection, table_name, file_name):
    file_path = DATA_DIR / file_name

    with file_path.open("r", encoding="utf-8-sig", newline="") as file:
        reader = csv.DictReader(file)
        rows = list(reader)

    if not rows:
        print(f"{table_name}: no rows to load.")
        return

    columns = list(rows[0].keys())

    if table_name == "transaction_fees":
        for row in rows:
            row.pop("fee_id", None)
        columns = list(rows[0].keys())
        for row in rows:
            row["currency"] = "INR"
        columns.append("currency")

    # fee_id is generated by PostgreSQL, not supplied by the CSV.
    column_sql = ", ".join(f'"{column}"' for column in columns)
    parameter_sql = ", ".join(f":{column}" for column in columns)

    statement = text(
        f'INSERT INTO "{table_name}" ({column_sql}) '
        f"VALUES ({parameter_sql})"
    )

    connection.execute(statement, rows)
    print(f"{table_name}: loaded {len(rows):,} rows.")


def main():
    engine = connect_to_database()

    try:
        with engine.begin() as connection:
            # Fail early if the database is not the expected one.
            database_name = connection.execute(
                text("SELECT current_database()")
            ).scalar_one()

            if database_name != "payment_intelligence":
                raise RuntimeError(
                    f"Unexpected database: {database_name}"
                )

            for table_name, file_name in TABLES:
                load_csv(connection, table_name, file_name)

        print("\nAll seven CSV files loaded successfully.")

    finally:
        engine.dispose()


if __name__ == "__main__":
    main()
